import { spawn } from 'node:child_process'
import { readdirSync } from 'node:fs'
import { homedir } from 'node:os'
import { delimiter, join, posix } from 'node:path'
import { killTree, toolEnv } from './ai/commitMessage'
import { resolveBinary } from './ai/detect'
import { buildInvocation } from './ai/tools'
import { AppError } from './git/errors'
import type { GitRunner } from './git/runner'

const REGENERATE_TIMEOUT_MS = 300_000

interface LockfileTool {
  binary: string
  /** Updates the lockfile to the manifests, keeping existing pins; runs no project scripts where the tool allows it. */
  args: readonly string[]
}

const LOCKFILE_TOOLS: Readonly<Record<string, LockfileTool>> = {
  'package-lock.json': { binary: 'npm', args: ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'] },
  // toolEnv sets CI=1, which would turn on pnpm's frozen lockfile.
  'pnpm-lock.yaml': { binary: 'pnpm', args: ['install', '--lockfile-only', '--ignore-scripts', '--ignore-pnpmfile', '--no-frozen-lockfile'] },
  // Not generate-lockfile: that upgrades every dependency.
  'Cargo.lock': { binary: 'cargo', args: ['update', '--workspace'] },
  'uv.lock': { binary: 'uv', args: ['lock'] }
}

const lockfileTool = (path: string): LockfileTool | undefined => {
  const name = posix.basename(path)
  return Object.hasOwn(LOCKFILE_TOOLS, name) ? LOCKFILE_TOOLS[name] : undefined
}

/** Conflicts in these files are regenerated by their package manager, without asking the AI. */
export function isLockfilePath(path: string): boolean {
  return lockfileTool(path) !== undefined
}

/** A GUI launch has neither cargo's nor nvm's bin on PATH, and nvm's are versioned. */
function findLockfileBinary(name: string): string | null {
  const home = (process.platform === 'win32' ? process.env.USERPROFILE : process.env.HOME) ?? homedir()
  let nvm: string[] = []
  try {
    const versions = join(home, '.nvm', 'versions', 'node')
    nvm = readdirSync(versions)
      .sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))
      .map((v) => join(versions, v, 'bin'))
  } catch {
    /* no nvm */
  }
  const PATH = [process.env.PATH ?? process.env.Path ?? '', join(home, '.cargo', 'bin'), ...nvm].join(delimiter)
  return resolveBinary([name], process.platform, { ...process.env, PATH, Path: PATH })
}

function runLockfileTool(binary: string, path: string, args: readonly string[], cwd: string, signal: AbortSignal | undefined, timeoutMs: number): Promise<void> {
  if (signal?.aborted) return Promise.reject(new AppError('Operation cancelled', 'CANCELLED'))
  return new Promise<void>((resolve, reject) => {
    const inv = buildInvocation(path, args)
    const child = spawn(inv.command, inv.args, {
      cwd,
      env: { ...toolEnv(path), ...inv.env },
      windowsHide: true,
      windowsVerbatimArguments: inv.windowsVerbatimArguments,
      detached: process.platform !== 'win32',
      stdio: ['ignore', 'ignore', 'pipe']
    })
    let stderr = ''
    let reason: 'cancelled' | 'timeout' | null = null
    const stop = (why: 'cancelled' | 'timeout'): void => {
      if (reason) return
      reason = why
      killTree(child.pid)
    }
    const onAbort = (): void => stop('cancelled')
    signal?.addEventListener('abort', onAbort, { once: true })
    const timer = setTimeout(() => stop('timeout'), timeoutMs)
    child.stderr.on('data', (c: Buffer) => {
      // Keep the tail only: that is where the useful error is.
      stderr = (stderr + c.toString('utf8')).slice(-8192)
    })
    let settled = false
    const finish = (code: number | null, spawnError?: Error): void => {
      if (settled) return
      settled = true
      clearTimeout(timer)
      signal?.removeEventListener('abort', onAbort)
      const tail = stderr.trim().split('\n').filter((l) => l.trim() !== '').slice(-3).join('\n')
      if (spawnError) reject(new AppError(`${binary} could not start: ${spawnError.message}`, 'UNKNOWN'))
      else if (reason === 'cancelled') reject(new AppError('Operation cancelled', 'CANCELLED'))
      else if (reason === 'timeout') reject(new AppError(`${binary} did not finish within ${Math.round(timeoutMs / 1000)} s`, 'UNKNOWN'))
      else if (code !== 0) reject(new AppError(`${binary} failed (exit code ${code})${tail ? `: ${tail}` : ''}`, 'UNKNOWN'))
      else resolve()
    }
    child.on('error', (e) => finish(null, e))
    child.on('close', (code) => finish(code))
  })
}

export interface RegenerateOptions {
  signal?: AbortSignal
  /** Finds the package manager (tests). */
  findBinary?: (name: string) => string | null
  timeoutMs?: number
}

/**
 * Resolves a conflicted lockfile with its package manager: starts from the
 * Yours side so existing pins survive, lets the tool bring it in line with the
 * manifests in the working tree, and stages the result. Run this after the
 * manifests are resolved. On any failure the conflict is restored.
 */
export async function regenerateLockfile(runner: GitRunner, root: string, rel: string, opts: RegenerateOptions = {}): Promise<void> {
  const tool = lockfileTool(rel)
  if (!tool) throw new AppError(`${rel} is not a known lockfile`, 'INVALID_ARGUMENT')
  const binary = (opts.findBinary ?? findLockfileBinary)(tool.binary)
  if (!binary) throw new AppError(`${tool.binary} was not found`, 'UNKNOWN')
  // Leaves the index stages in place, so checkout -m can bring the conflict back.
  await runner.run(['checkout', '--ours', '--', rel], { cwd: root })
  try {
    await runLockfileTool(tool.binary, binary, tool.args, join(root, posix.dirname(rel)), opts.signal, opts.timeoutMs ?? REGENERATE_TIMEOUT_MS)
    await runner.run(['add', '--', rel], { cwd: root })
  } catch (e) {
    await runner.run(['checkout', '-m', '--', rel], { cwd: root })
    throw e
  }
}
